import {readFile,writeFile,readdir} from 'node:fs/promises';
import {stations,legacyStores} from '../data/catalog.mjs';
const read=async path=>JSON.parse(await readFile(path,'utf8'));
const coordinates=await read('data/station-coordinates.json');
const files=(await readdir('data')).filter(f=>/^branches-(?!all).*\.json$/.test(f));
const branches=(await Promise.all(files.map(f=>read('data/'+f)))).flat();
const flyers=await read('data/flyers.json').catch(()=>[]);
const canonical=url=>decodeURI(url).replace(/\/$/,'').toLowerCase();
const normalized=value=>value.normalize('NFKC').replace(/\s/g,'');
function distance(a,b){const rad=n=>n*Math.PI/180;const dlat=rad(b.lat-a.lat),dlon=rad(b.lon-a.lon);return 6371000*2*Math.asin(Math.sqrt(Math.sin(dlat/2)**2+Math.cos(rad(a.lat))*Math.cos(rad(b.lat))*Math.sin(dlon/2)**2));}
function publishedWalk(s,b){
 const ja=s.ja.split('〈')[0];
 const escaped=ja.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
 const match=b.accessText?.match(new RegExp('(?:線|(?<![一-龯ぁ-んァ-ヶ]))'+escaped+'駅[^。;]{0,45}?徒歩(?:約)?\\s*(\\d+)\\s*分'));
 return match ? Number(match[1]) : null;
}
const byUrl=new Map(branches.map(b=>[canonical(b.url),b]));
// Retain independently checked pilot shops and exact published walk estimates.
for(const old of legacyStores){
 const key=canonical(old.url);let b=byUrl.get(key)||branches.find(b=>b.chain===old.chain&&normalized(b.ja)===normalized(old.ja));
 if(!b){b={...old,branchId:old.id,stationIds:[old.station],checkedAt:'2026-10-09T00:00:00+09:00',flyerUrl:old.chain==='ok'?'https://ok-corporation.jp/flyer/':old.url,provenance:'manual-official'};byUrl.set(key,b);}
 b.legacyAccess??={};b.legacyAccess[old.station]={walk:old.walk,access:old.access};
}
const unique=[...byUrl.values()];
const associations=[];
for(const s of coordinates){
 const nearby=unique.filter(b=>(b.lat&&b.lon&&distance(s,b)<=2500)||b.stationIds?.includes(s.id)||b.legacyAccess?.[s.id]);
 for(const b of nearby){
  const legacy=b.legacyAccess?.[s.id];const walk=legacy?.walk??publishedWalk(s,b);
  associations.push({branchId:b.branchId,station:s.id,walk,distanceMeters:b.lat?Math.round(distance(s,b)):null,access:legacy?.access||(walk!==null?'Official walking estimate':b.coordinatePrecision==='map-center'?'Approximate map vicinity':'Straight-line estimate; walking route may be longer')});
 }
}
const counts=stations.map(s=>({id:s.id,name:s.name,ja:s.ja,shops:associations.filter(a=>a.station===s.id).length}));
const latestCheck=new Date(Math.max(...unique.map(b=>Date.parse(b.checkedAt)),...flyers.map(f=>Date.parse(f.checkedAt)))).toISOString();
const summary={branches:unique.length,stations:stations.length,stationsWithFive:counts.filter(s=>s.shops>=5).length,stationCounts:counts,flyers:flyers.length,flyerBranches:new Set(flyers.map(f=>f.branchId)).size,radiusMeters:2500,checkedAt:latestCheck};
// Branch facts are stored once; station-specific distance/access is a separate relation.
await writeFile('data/researched.mjs','// Generated by scripts/compile-research.mjs; edit adapters or manual facts.\nexport const branches='+JSON.stringify(unique)+';\nconst associations='+JSON.stringify(associations)+';\nconst byId=new Map(branches.map(b=>[b.branchId,b]));\nexport const researchedStores=associations.map(a=>({...byId.get(a.branchId),...a,id:a.branchId+"--"+a.station}));\nexport const researchSummary='+JSON.stringify(summary)+';\n');
await writeFile('data/research-summary.json',JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify({branches:summary.branches,associations:associations.length,stationsWithFive:summary.stationsWithFive,flyerBranches:summary.flyerBranches,gaps:counts.filter(s=>s.shops<5)}));
